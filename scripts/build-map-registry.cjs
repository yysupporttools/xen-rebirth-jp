const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const ctx = {window: {}};
vm.runInNewContext(fs.readFileSync(path.join(root, 'dist/assets/world-routes.js'), 'utf8'), ctx);
const routes = ctx.window.XEN_WORLD_ROUTES;
const key = text => String(text || '').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]/gu, '');
const names = [...routes.nodes, 'City Hall', 'Cobalt\'s Cave', 'Amorica Cave', 'Mythril Mines', 'Pirate Ship', 'Labyrinth', 'Museidon Library Labyrinth', 'Ice Caves', 'Lost Brynhilld', 'Memorial Chapel', 'Secret Altar', 'Knight\'s Convention', 'Brynhilld Culvert B1F', 'Brynhilld Culvert B2F', 'Cave to Brynhilld Altar'];
const aliases = Object.create(null);
for (const name of names) aliases[key(name)] = name;
for (const [alias, canonical] of Object.entries(routes.aliases)) aliases[key(alias)] = canonical;
const verified = {
  // Game MAP titles supplied by the site owner take precedence over website spelling.
  'Bradley Forest': 'Bradlely Forest',
  'Theglia Forest': 'Theglaia Forest',
  'Costella Forest': 'Castella Forest',
  'Toisen Plains': 'Taisen Plains',
  'Chingon Plains': 'Clingon Plains',
  'Rosestar Basin': 'Rosetar Basin',
  'Pladino Grove': 'Paladino Grove',
  'Ashley Forest': 'Ashely Forest',
  'Sylphaen Forest': 'Shylphaen Forest',
  'Arcana Square': 'Arcarinas Square', "Arcana's Square": 'Arcarinas Square', 'Arcania Square': 'Arcarinas Square', "Arcania's Square": 'Arcarinas Square',
  'Arcanus Square': 'Arcarinas Square', "Arcaria's Square": 'Arcarinas Square', 'Arcarias Square': 'Arcarinas Square',
  'Brunnen Basin': 'Brunen Basin', 'Brynhilld': 'Arcarinas Square', 'Brynhild': 'Arcarinas Square', 'Brinhilld': 'Arcarinas Square', 'Brynnhild': 'Arcarinas Square', 'Brynhildr': 'Arcarinas Square',
  'Brynhild Trisects': 'Brynhildr Trisects', 'Brynhilld Trisects': 'Brynhildr Trisects', 'Brynhild T-sects': 'Brynhildr Trisects',
  'Candyvault': 'Candy Vault', 'Village of Abundance': 'Abundance Town', 'Albatross Village': 'Albatross City',
  'Titans Plains': 'Titanus Plains', 'Titarius Plains': 'Titanus Plains', 'Titanus Plain': 'Titanus Plains', 'Jotunnheim': 'Jotunheim',
  'ブリンヒルド': 'Arcarinas Square', 'エスネ': 'Essene', 'エイル': 'Eir', 'ヨツンハイム': 'Jotunheim', 'オアシス': 'Oasis'
};
for (const [alias, canonical] of Object.entries(verified)) aliases[key(alias)] = canonical;
const japanese = JSON.parse(fs.readFileSync(path.join(root, 'dist/assets/map-japanese-names.json'), 'utf8'));
for (const [canonical, oldJapanese] of Object.entries(japanese.names)) {
  if (!names.includes(canonical)) throw new Error('Unregistered Japanese counterpart: '+canonical);
  if (!oldJapanese.trim()) throw new Error('Empty old Japanese name: '+canonical);
  const aliasKey=key(oldJapanese);
  if (aliases[aliasKey] && aliases[aliasKey] !== canonical) throw new Error('Ambiguous old Japanese name: '+oldJapanese);
  aliases[aliasKey]=canonical;
}
const registry = {version: 4, source: 'Pre-registered world routes, game-confirmed names, verified capture spelling aliases and reviewed old Japanese map names', names: [...new Set(names)].sort(), aliases};
fs.writeFileSync(path.join(root, 'dist/assets/map-registry-data.json'), JSON.stringify(registry, null, 2) + '\n');
const runtime = fs.readFileSync(path.join(__dirname, 'map-registry-runtime.js'), 'utf8');
fs.writeFileSync(path.join(root, 'dist/assets/map-registry.js'), '/* Generated by scripts/build-map-registry.cjs. */\n' + runtime.replace('/* REGISTRY_DATA */', JSON.stringify(registry)));
const japaneseRuntime = fs.readFileSync(path.join(__dirname, 'map-japanese-names-runtime.js'), 'utf8');
fs.writeFileSync(path.join(root, 'dist/assets/map-japanese-names.js'), '/* Generated from reviewed map-japanese-names.json. */\n'+japaneseRuntime.replace('/* JAPANESE_MAP_DATA */{names:{}}', JSON.stringify(japanese)));
console.log(`${registry.names.length} registered maps / ${Object.keys(aliases).length} normalized names`);
